const ENTITY_CHARS = 'PScbfBDH+Avtgr';

// Convierte los mapas de texto en datos utilizables.
export function loadRoom(def) {
  const w = def.w * SCREEN_W, h = def.h * SCREEN_H;
  const tiles = [], spawns = [], decor = [];
  for (let j = 0; j < h; j++) {
    const row = def.map[j] || '';
    let out = '';
    for (let i = 0; i < w; i++) {
      const ch = row[i] || '#';
      if (ENTITY_CHARS.includes(ch)) {
        out += '.';
        if ('vtgr'.includes(ch)) decor.push({ type: ch, i, j });
        else spawns.push({ type: ch, i, j });
      } else out += ch;
    }
    tiles.push(out.split(''));
  }
  return {
    ...def, w, h, tiles, spawns, decor,
    px: def.x * SCREEN_W * 16, py: def.y * SCREEN_H * 16,
  };
}

export function roomAt(rooms, wx, wy) {
  for (const r of rooms) {
    if (wx >= r.px && wy >= r.py && wx < r.px + r.w * 16 && wy < r.py + r.h * 16) return r;
  }
  return null;
}
